create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique
);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id),
  name text not null unique,
  description text not null default '',
  price_cents integer not null check (price_cents > 0),
  image_url text,
  product_type text not null default 'tee' check (product_type in ('tee','hoodie','pants','shorts','jacket','cap')),
  color text not null default '#68735c',
  badge text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  size text not null check (size in ('S','M','L','XL','One size')),
  stock integer not null default 0 check (stock >= 0),
  unique (product_id,size)
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  access_token_hash text not null,
  customer_name text not null,
  customer_email text not null,
  street text not null,
  postal_code text not null,
  city text not null,
  country text not null check (country in ('NL','BE')),
  subtotal_cents integer not null check (subtotal_cents > 0),
  shipping_cents integer not null check (shipping_cents >= 0),
  total_cents integer not null check (total_cents = subtotal_cents + shipping_cents),
  payment_method text not null default 'bank_transfer' check (payment_method='bank_transfer'),
  payment_status text not null default 'awaiting_transfer' check (payment_status in ('awaiting_transfer','paid','canceled','expired')),
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  product_name text not null,
  size text not null,
  quantity integer not null check (quantity > 0),
  unit_price_cents integer not null check (unit_price_cents > 0)
);
create index if not exists products_category_id_idx on public.products(category_id);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists order_items_order_id_idx on public.order_items(order_id);

alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.product_variants enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
drop policy if exists "Public can read categories" on public.categories;
create policy "Public can read categories" on public.categories for select to anon,authenticated
  using (exists(select 1 from public.products p where p.category_id=categories.id and p.active));
drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products" on public.products for select to anon,authenticated using(active);
drop policy if exists "Public can read active product sizes" on public.product_variants;
create policy "Public can read active product sizes" on public.product_variants for select to anon,authenticated
  using(exists(select 1 from public.products p where p.id=product_variants.product_id and p.active));
-- Er zijn bewust geen browser policies voor orders en orderregels.
revoke all on public.categories,public.products,public.product_variants,public.orders,public.order_items from anon,authenticated,service_role;
grant select on public.categories,public.products,public.product_variants,public.orders to service_role;

create or replace function public.expire_transfer_orders()
returns integer language plpgsql security definer set search_path=public as $$
declare v_order record; v_count integer:=0;
begin
  for v_order in select id from public.orders
    where payment_status='awaiting_transfer' and expires_at<=now() for update skip locked
  loop
    update public.orders set payment_status='expired' where id=v_order.id;
    update public.product_variants pv set stock=pv.stock+oi.quantity from public.order_items oi
      where oi.order_id=v_order.id and pv.product_id=oi.product_id and pv.size=oi.size;
    v_count:=v_count+1;
  end loop;
  return v_count;
end;
$$;

create or replace function public.create_pending_order(p_customer jsonb,p_items jsonb,p_access_token_hash text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  v_item jsonb; v_product record; v_product_id bigint; v_quantity integer; v_size text;
  v_lines jsonb:='[]'::jsonb; v_subtotal integer:=0; v_shipping integer;
  v_order_id uuid; v_order_number text; v_expires_at timestamptz:=now()+interval '48 hours';
begin
  perform public.expire_transfer_orders();
  if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)<1 or jsonb_array_length(p_items)>20 then
    raise exception 'Cart is invalid';
  end if;
  if length(coalesce(p_access_token_hash,''))<>64 then raise exception 'Access token is invalid'; end if;
  if (select count(*) from public.orders where customer_email=lower(trim(p_customer->>'email'))
      and created_at>now()-interval '1 hour')>=5 then raise exception 'Order rate limit reached'; end if;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_product_id:=(v_item->>'product_id')::bigint;
    v_quantity:=(v_item->>'quantity')::integer;
    v_size:=v_item->>'size';
    if v_quantity<1 or v_quantity>10 or v_size not in ('S','M','L','XL','One size') then raise exception 'Item is invalid'; end if;
    select p.id,p.name,p.price_cents,pv.stock into v_product
      from public.products p join public.product_variants pv on pv.product_id=p.id and pv.size=v_size
      where p.id=v_product_id and p.active for update of pv;
    if not found then raise exception 'Product unavailable'; end if;
    if v_product.stock<v_quantity then raise exception 'Insufficient stock'; end if;
    update public.product_variants set stock=stock-v_quantity where product_id=v_product_id and size=v_size;
    v_subtotal:=v_subtotal+v_product.price_cents*v_quantity;
    v_lines:=v_lines||jsonb_build_array(jsonb_build_object('product_id',v_product_id,
      'product_name',v_product.name,'size',v_size,'quantity',v_quantity,'unit_price_cents',v_product.price_cents));
  end loop;
  v_shipping:=case when v_subtotal>=10000 then 0 else 495 end;
  v_order_number:='SML-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,10));
  insert into public.orders(order_number,access_token_hash,customer_name,customer_email,street,postal_code,city,
    country,subtotal_cents,shipping_cents,total_cents,expires_at)
  values(v_order_number,p_access_token_hash,trim(p_customer->>'name'),lower(trim(p_customer->>'email')),
    trim(p_customer->>'street'),upper(trim(p_customer->>'postal_code')),trim(p_customer->>'city'),
    p_customer->>'country',v_subtotal,v_shipping,v_subtotal+v_shipping,v_expires_at) returning id into v_order_id;
  insert into public.order_items(order_id,product_id,product_name,size,quantity,unit_price_cents)
    select v_order_id,(line->>'product_id')::bigint,line->>'product_name',line->>'size',
      (line->>'quantity')::integer,(line->>'unit_price_cents')::integer from jsonb_array_elements(v_lines) line;
  return jsonb_build_object('id',v_order_id,'order_number',v_order_number,'subtotal_cents',v_subtotal,
    'shipping_cents',v_shipping,'total_cents',v_subtotal+v_shipping,'expires_at',v_expires_at);
end;
$$;

create or replace function public.cancel_unpaid_order(p_order_number text)
returns void language plpgsql security definer set search_path=public as $$
declare v_order public.orders%rowtype;
begin
  perform public.expire_transfer_orders();
  select * into v_order from public.orders where order_number=p_order_number for update;
  if not found or v_order.payment_status<>'awaiting_transfer' then raise exception 'Order is not awaiting transfer'; end if;
  update public.orders set payment_status='canceled' where id=v_order.id;
  update public.product_variants pv set stock=pv.stock+oi.quantity from public.order_items oi
    where oi.order_id=v_order.id and pv.product_id=oi.product_id and pv.size=oi.size;
end;
$$;

create or replace function public.mark_order_paid(p_order_number text)
returns void language plpgsql security definer set search_path=public as $$
declare v_order public.orders%rowtype;
begin
  perform public.expire_transfer_orders();
  select * into v_order from public.orders where order_number=p_order_number for update;
  if not found or v_order.payment_status<>'awaiting_transfer' then raise exception 'Order is not awaiting transfer'; end if;
  update public.orders set payment_status='paid' where id=v_order.id;
end;
$$;

revoke all on function public.expire_transfer_orders() from public,anon,authenticated;
revoke all on function public.create_pending_order(jsonb,jsonb,text) from public,anon,authenticated;
revoke all on function public.cancel_unpaid_order(text) from public,anon,authenticated;
revoke all on function public.mark_order_paid(text) from public,anon,authenticated;
grant execute on function public.expire_transfer_orders() to service_role;
grant execute on function public.create_pending_order(jsonb,jsonb,text) to service_role;
grant execute on function public.cancel_unpaid_order(text) to service_role;
grant execute on function public.mark_order_paid(text) to service_role;
